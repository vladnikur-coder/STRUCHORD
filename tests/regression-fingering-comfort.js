w.addEventListener('load', () => {
  console.log('=== 1. Калибровочные пары (вердикты гитариста) ===');
  let pairBad = 0;
  for (const [chord, a, b, expect] of PAIRS) {
    const r = w.eval(`(function(){
      const ks = getKeyStyle('C');
      const main = ${JSON.stringify(chord)}.split('/')[0];
      const notes = getChordNotes(main, ks) || [];
      const root = (notes[0] || '').replace(/\\d+$/, '');
      const score = (str) => scoreShape(str.split(',').map(v => v === 'x' ? 'x' : Number(v)), notes, root, null);
      return { sa: score(${JSON.stringify(a)}), sb: score(${JSON.stringify(b)}) };
    })()`);
    const pass =
      expect === 'A' ? r.sa > r.sb : expect === 'B' ? r.sb > r.sa : r.sb >= r.sa;
    if (!pass) {
      pairBad++;
      bad++;
      console.log(
        `   FAIL [${chord}] ${a} vs ${b} — ждали ${expect}, ` +
          `очки ${Math.round(r.sa * 10) / 10} / ${Math.round(r.sb * 10) / 10}`
      );
    }
  }
  ok(`все ${PAIRS.length} пар совпали`, pairBad === 0, `${pairBad} не совпали`);

  console.log('\n=== 2. Топ выдачи Aadd9 (флагманская жалоба) ===');
  const top = w.eval(`(function(){
    const v = getFingeringVariants('Aadd9','C');
    return v.shapes.slice(0, 5).map(s => s.join(','));
  })()`);
  console.log('      топ-5: ' + top.join(' | '));
  ok('первой идёт x,0,7,6,0,0', top[0] === 'x,0,7,6,0,0', top[0]);
  ok('второй идёт 5,7,7,6,0,0', top[1] === '5,7,7,6,0,0', top[1]);
  ok('неиграбельной 5,2,2,2,2,0 нет в топ-5', !top.slice(0, 5).includes('5,2,2,2,2,0'));

  console.log('\n=== 3. Бан-лист не всплывает первым ===');
  const firsts = w.eval(`(function(){
    const get = (c) => getFingeringVariants(c, 'C').shapes[0].join(',');
    return { D7: get('D7'), G: get('G'), C9: get('C9'), F: get('F'), Bb: get('Bb') };
  })()`);
  ok('D7 первым идёт открытая', firsts.D7 === 'x,x,0,2,1,2', firsts.D7);
  // Стена open подтверждена уточнённой волной-4 (2026-08-13): табличная
  // 3,2,0,0,3,3 снова первой; 3,2,0,0,0,3 (57.4 против 53.2) допустима
  // как вариант, если порядок изменится честной причиной. Обе —
  // распевочный открытый G, дух правила — «открытая первая».
  ok('G первым идёт открытая', firsts.G === '3,2,0,0,0,3' || firsts.G === '3,2,0,0,3,3', firsts.G);
  ok('C9 первой идёт джаз-девятка', firsts.C9 === 'x,3,2,3,3,3', firsts.C9);
  ok('F первым идёт E-форма баррэ', firsts.F === '1,3,3,2,1,1', firsts.F);
  ok('Bb первым идёт E-форма на 6 (пара калибровки)', firsts.Bb === '6,8,8,7,6,6', firsts.Bb);

  console.log('\n=== 4. Волна-2: позиционные вердикты ===');
  const w2 = w.eval(`(function(){
    const v = (c) => getFingeringVariants(c, 'C').shapes.map(s => s.join(','));
    return { E6: v('E6'), E6m: getFingeringVariants('E6','C').methods,
             G9: v('G9'), A7sus4: v('A7sus4'), Dm7sus4: null, D7sus4: v('D7sus4'), Dshin: v('D#m7') };
  })()`);
  // ВЕРДИКТ q34b ВОЗВРАЩЁН волной-6 (2026-08-14, дословно: «Всё-таки
  // нужен порядок OPEN - CAGED - Всё остальное»): у E6 нет табличной
  // open-формы, поэтому первой снова идёт верхняя CAGED
  // 0,7,9,9,9,9 (17.8) — как он просил в q34b («музыкально удачнее»);
  // самая удобная 0,7,6,6,0,0 (32.8) — второй, на вершине блока
  // «всё остальное». Волна-4 держала обратное только потому, что
  // слила CAGED с авто в общий пул.
  ok('E6 первой идёт caged 0,7,9,9,9,9 (волна-6: блок OPEN-CAGED-остальное)',
    w2.E6[0] === '0,7,9,9,9,9', w2.E6[0]);
  const e6idx = w2.E6.indexOf('0,7,6,6,0,0');
  ok('E6: 0,7,6,6,0,0 — вершина блока «остальное» (сразу после всех caged)',
    e6idx > 0 && w2.E6m.slice(0, e6idx).every((m) => m === 'caged') &&
    w2.E6m[e6idx] !== 'caged',
    'поз. ' + (e6idx + 1) + ' метод=' + w2.E6m[e6idx]);
  // G9: народная открытая форма впереди caged.
  ok('G9 первой идёт народная 3,0,0,0,0,1', w2.G9[0] === '3,0,0,0,0,1', w2.G9[0]);
  // q35b: минималка — дубль того же семейства, ниже топ-3; допустимо и
  // полное отсутствие в списке (дедуп по хвату отдаёт слот лучшей
  // сестре x,0,x,0,3,0, раз OPEN_DRONE честно снял с минималки бонус).
  ok('A7sus4: минималка x,0,0,0,3,0 отсутствует или ниже топ-3',
    w2.A7sus4.indexOf('x,0,0,0,3,0') === -1 || w2.A7sus4.indexOf('x,0,0,0,3,0') > 2,
    'поз. ' + (w2.A7sus4.indexOf('x,0,0,0,3,0') + 1));
  ok('A7sus4: полная x,0,2,0,3,0 выше минималки в выдаче',
    w2.A7sus4.indexOf('x,0,2,0,3,0') !== -1 &&
    (w2.A7sus4.indexOf('x,0,0,0,3,0') === -1 ||
      w2.A7sus4.indexOf('x,0,2,0,3,0') < w2.A7sus4.indexOf('x,0,0,0,3,0')),
    'поз. ' + (w2.A7sus4.indexOf('x,0,2,0,3,0') + 1) + ' vs ' + (w2.A7sus4.indexOf('x,0,0,0,3,0') + 1));
  // Тяжёлая 11,9,11,8,11,11 (-25.2; анализатор хвата НЕ банит — это не
  // cls2, а очень низкая оценка). Волна-6 вернула ступень CAGED
  // целиком, поэтому она вновь стоит на стыке блоков — 4-й позицией,
  // НИЖЕ всех полноценных caged (21.6/18.4/13.9), но выше авто-пула.
  // Это известная цена жёлтой ступени (та же 4-я позиция была при
  // старой форе). Зафиксировано: первой не всплывает никогда; если
  // гитарист скажет «такую дичь не показывай вовсе» — будет отдельное
  // правило-водораздел по порогу очков для подъёма в CAGED-блок.
  ok('D#m7: тяжёлая 11,9,11,8,11,11 ниже всех полноценных caged и не в топ-3',
    w2.Dshin.indexOf('11,9,11,8,11,11') >= 3 &&
    w2.Dshin.indexOf('11,9,11,8,11,11') < w2.Dshin.indexOf('11,x,11,11,11,11'),
    'поз. ' + (w2.Dshin.indexOf('11,9,11,8,11,11') + 1));

  console.log(bad ? `\nПРОВАЛОВ: ${bad}` : '\nвсе проверки пройдены');
  if (bad) process.exitCode = 1;
});
